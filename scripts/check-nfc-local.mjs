async function request(path, { method="GET", body, admin=false, origin=base } = {}) {
  const headers = { ...(body !== undefined ? {"Content-Type":"application/json"} : {}), ...(method !== "GET" ? {Origin:origin} : {}), ...(admin ? {Cookie:cookie} : {}) };
  return fetch(base+path, {method,headers,body:body===undefined?undefined:JSON.stringify(body),redirect:"manual"});
}
